function ensureModalTextContainer() {

  const old =
    $("rewardModalText");


  if (!old) {
    return null;
  }


  if (
    old.tagName === "DIV"
  ) {

    return old;
  }


  const replacement =
    document.createElement(
      "div"
    );


  replacement.id =
    "rewardModalText";


  replacement.className =
    old.className;


  old.replaceWith(
    replacement
  );


  return replacement;

}



