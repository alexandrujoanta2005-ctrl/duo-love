/* =========================================================
   FORMAT DATĂ
========================================================= */

function formatDate(
  value
) {

  if (!value) {
    return "";
  }


  const date =
    new Date(
      `${value}T00:00:00`
    );


  return Number.isNaN(
    date.getTime()
  )
    ? value
    : date.toLocaleDateString(
        "ro-RO",
        {
          day: "numeric",
          month: "long",
          year: "numeric"
        }
      );

}



/* =========================================================
   FORMAT DATĂ + ORĂ
========================================================= */

function formatDateTime(
  value
) {

  if (!value) {
    return "";
  }


  const date =
    new Date(value);


  return Number.isNaN(
    date.getTime()
  )
    ? ""
    : date.toLocaleString(
        "ro-RO",
        {
          day: "2-digit",
          month: "2-digit",
          hour: "2-digit",
          minute: "2-digit"
        }
      );

}



