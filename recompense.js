/* =========================================================
   DETALII MAGAZIN
========================================================= */

function parseDetails(
  value
) {

  if (
    Array.isArray(value)
  ) {

    return value;
  }


  if (!value) {

    return [];
  }


  if (
    typeof value === "string"
  ) {

    try {

      const parsed =
        JSON.parse(value);


      return Array.isArray(parsed)
        ? parsed
        : [value];

    } catch {

      return [value];

    }

  }


  return [];

}



