function toggleFeature(
  id,
  unlocked,
  threshold
) {

  const element =
    $(id);


  if (!element) {
    return;
  }


  element.classList.toggle(
    "feature-locked",
    !unlocked
  );


  const lock =
    element.querySelector(
      ".feature-lock-overlay"
    );


  if (!lock) {
    return;
  }


  lock.hidden =
    unlocked;


  const text =
    lock.querySelector(
      "span"
    );


  if (text) {

    text.textContent =
      `Se deblochează la ${threshold} XP`;

  }

}



