function showRewardBubble(
  icon,
  title,
  text,
  duration = 3200
) {

  const bubble =
    ensureRewardBubble();


  $("rewardTopBubbleIcon")
    .textContent =
    icon || "🎁";


  $("rewardTopBubbleTitle")
    .textContent =
    title || "Recompensă";


  $("rewardTopBubbleText")
    .textContent =
    text || "";


  clearTimeout(
    rewardBubbleTimer
  );


  bubble.classList.remove(
    "show"
  );


  void bubble.offsetWidth;


  bubble.classList.add(
    "show"
  );


  rewardBubbleTimer =
    setTimeout(
      function () {

        bubble.classList.remove(
          "show"
        );

      },
      duration
    );

}



/* =========================================================
   VERIFICĂ RECOMPENSE NOI
========================================================= */

function checkNewXPRewards(
  totalXP
) {

  const key =
    "rewardLastSeenTotalXP";


  const saved =
    localStorage.getItem(
      key
    );


  if (
    saved === null
  ) {

    localStorage.setItem(
      key,
      String(totalXP)
    );

    return;
  }


  const oldXP =
    Number(saved) || 0;


  if (
    totalXP <= oldXP
  ) {
    return;
  }


  const newlyUnlocked =
    XP_REWARDS.filter(
      reward =>
        reward.xp > oldXP &&
        reward.xp <= totalXP
    );


  localStorage.setItem(
    key,
    String(totalXP)
  );


  if (
    !newlyUnlocked.length
  ) {
    return;
  }


  const latest =
    newlyUnlocked[
      newlyUnlocked.length - 1
    ];


  if (
    newlyUnlocked.length === 1
  ) {

    showRewardBubble(
      latest.icon,
      "Recompensă nouă!",
      `${latest.title} · ${latest.xp} XP`
    );

  } else {

    showRewardBubble(
      "🎁",
      `${newlyUnlocked.length} recompense noi!`,
      `Cea mai nouă: ${latest.title} · ${latest.xp} XP`,
      3800
    );

  }

}



/* =========================================================
   AUTENTIFICARE
========================================================= */

async function requireAuth() {

  if (
    typeof supabaseClient ===
    "undefined"
  ) {
    return false;
  }


  const {
    data,
    error
  } =
    await supabaseClient
      .auth
      .getSession();


  if (
    error ||
    !data?.session
  ) {

    window.location.replace(
      "./login.html"
    );

    return false;
  }


  return true;

}



